"""Generate the pre-rasterized text font used by the round display.

Usage: python3 firmware/tools/generate_text_font.py path/to/Roboto-Bold.ttf
Covers printable ASCII. Glyphs are rendered larger than any on-screen use,
so the firmware only ever scales them down; the 4-bit anti-aliased coverage
needs no runtime TrueType parser or font file. Uses the glyph layout of
numeric_font.h (generate_numeric_font.py).
"""

from pathlib import Path
import sys

from PIL import Image, ImageDraw, ImageFont


CHARS = "".join(chr(code) for code in range(32, 127))
# Cap height about 64 px: above the largest text on the panel (~60 px).
SIZE = 90
OUT = Path(__file__).resolve().parents[1] / "esp32_nav_display" / "text_font.h"


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit("usage: generate_text_font.py Roboto-Bold.ttf")
    font = ImageFont.truetype(sys.argv[1], SIZE)
    data = []
    glyphs = []
    ascent, descent = font.getmetrics()
    pad = SIZE // 2
    for char in CHARS:
        # Render with room on every side and crop to the ink: Pillow's bbox is
        # the advance box, which would cut overhanging strokes (A, V, y, ...).
        advance = font.getlength(char)
        canvas = Image.new("L", (int(advance) + 2 * pad,
                                 ascent + descent + 2 * pad))
        origin = (pad, pad + ascent)
        ImageDraw.Draw(canvas).text(origin, char, font=font, anchor="ls",
                                    fill=255)
        ink = canvas.getbbox()
        offset = len(data)
        if ink:
            image = canvas.crop(ink)
            width, height = image.size
            left, top = ink[0] - origin[0], ink[1] - origin[1]
            alpha = [round(value * 15 / 255) for value in image.getdata()]
            data.extend((alpha[index] << 4) | (alpha[index + 1]
                        if index + 1 < len(alpha) else 0)
                        for index in range(0, len(alpha), 2))
        else:
            width = height = left = top = 0
        glyphs.append((ord(char), width, height, left, top,
                       round(advance), offset))
    for _, width, height, left, top, advance, _ in glyphs:
        assert 0 <= width < 256 and 0 <= height < 256 and 0 <= advance < 256
        assert -128 <= left < 128 and -128 <= top < 128
    cap_height = -font.getbbox("H", anchor="ls")[1]

    name = " ".join(font.getname())
    lines = [
        f"// Generated by firmware/tools/generate_text_font.py from {name}.",
        "// Roboto is licensed under Apache License 2.0. Do not edit by hand.",
        "#pragma once",
        "#include <stdint.h>",
        '#include "numeric_font.h"  // NavoNumericGlyph',
        f"static constexpr uint8_t NAVO_TEXT_CAP_HEIGHT = {cap_height};",
        "static const NavoNumericGlyph NAVO_TEXT_GLYPHS[] = {",
    ]
    for code, width, height, left, top, advance, offset in glyphs:
        lines.append(f"  {{{code}, {width}, {height}, {left}, {top}, "
                     f"{advance}, {offset}}},")
    lines += ["};", "static const uint8_t NAVO_TEXT_ALPHA[] = {"]
    for index in range(0, len(data), 24):
        lines.append("  " + ", ".join(f"0x{value:02x}"
                                    for value in data[index:index + 24]) + ",")
    lines += ["};", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({len(glyphs)} glyphs, {len(data)} packed alpha bytes, "
          f"cap height {cap_height})")


if __name__ == "__main__":
    main()
