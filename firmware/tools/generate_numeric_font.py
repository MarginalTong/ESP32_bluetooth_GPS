"""Generate the small, pre-rasterized numeric font used by the round display.

Usage: python3 firmware/tools/generate_numeric_font.py path/to/Roboto-Medium.ttf
The generated header has 4-bit anti-aliased coverage, so firmware needs no
runtime TrueType parser or font file.
"""

from pathlib import Path
import sys

from PIL import Image, ImageDraw, ImageFont


CHARS = "0123456789:."
SIZE = 110
OUT = Path(__file__).resolve().parents[1] / "esp32_nav_display" / "numeric_font.h"


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit("usage: generate_numeric_font.py Roboto-Regular.ttf")
    font = ImageFont.truetype(sys.argv[1], SIZE)
    data = []
    glyphs = []
    for char in CHARS:
        left, top, right, bottom = font.getbbox(char, anchor="ls")
        width, height = right - left, bottom - top
        image = Image.new("L", (width, height))
        ImageDraw.Draw(image).text((-left, -top), char, font=font,
                                   anchor="ls", fill=255)
        alpha = [round(value * 15 / 255) for value in image.getdata()]
        offset = len(data)
        data.extend((alpha[index] << 4) | (alpha[index + 1]
                    if index + 1 < len(alpha) else 0)
                    for index in range(0, len(alpha), 2))
        glyphs.append((char, width, height, left, top,
                       round(font.getlength(char)), offset))

    lines = [
        "// Generated by firmware/tools/generate_numeric_font.py from Roboto Medium.",
        "// Roboto is licensed under Apache License 2.0. Do not edit by hand.",
        "#pragma once",
        "#include <stdint.h>",
        "struct NavioNumericGlyph {",
        "  char code; uint8_t width, height; int8_t xOffset, yOffset;",
        "  uint8_t advance; uint32_t offset;",
        "};",
        "static constexpr uint8_t NAVIO_NUMERIC_CAP_HEIGHT = 79;",
        "static const NavioNumericGlyph NAVIO_NUMERIC_GLYPHS[] = {",
    ]
    for char, width, height, left, top, advance, offset in glyphs:
        lines.append(f"  {{'{char}', {width}, {height}, {left}, {top}, "
                     f"{advance}, {offset}}},")
    lines += ["};", "static const uint8_t NAVIO_NUMERIC_ALPHA[] = {"]
    for index in range(0, len(data), 24):
        lines.append("  " + ", ".join(f"0x{value:02x}"
                                    for value in data[index:index + 24]) + ",")
    lines += ["};", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({len(data)} packed alpha bytes)")


if __name__ == "__main__":
    main()
